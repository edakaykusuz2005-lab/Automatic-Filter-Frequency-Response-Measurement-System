/* USER CODE BEGIN 4 */
static float CalculateRms(float *pData, uint32_t size){
    float mean = 0.0f;
    float sum = 0.0f;
    float sizeF = size;

    // Calculate DC offset
    for(uint32_t i = 0; i < size; i++)
    {
        mean += pData[i];
    }

    mean /= sizeF;

    // Calculate RMS
    for(uint32_t i = 0; i < size; i++)
    {
        float v = pData[i] - mean;
        sum += (v * v);
    }

    return (sqrtf(sum / sizeF) * 0.7326f);
}

